"""Generate extension/src/lib/targets/a1-profiles.js from Bambu Studio A1 project files.

Usage: python3 -I scripts/extract_a1_profiles.py <folder with the A1 sample .3mf files>

Each source entry names the project file and filament index a preset is read from.
Only Metadata/project_settings.config is read; nothing in the archives is executed.
"""
import json
import os
import sys
import zipfile

BASE_FILE = "llaveros_teclas_2_a1.3mf"  # uses "0.20mm A1 - principal"

PRINT_SOURCES = {
    "0.20mm A1 - principal": "llaveros_teclas_2_a1.3mf",
    "0.20mm A1 - alisado eSUN": "paint_princesas-A1.3mf",
}

FILAMENT_SOURCES = {
    "eSUN - PLA+ 2025": ("llaveros_teclas_2_a1.3mf", 1),
    "Elegoo PLA+": ("llaveros_teclas_2_a1.3mf", 0),
    "Elegoo Rapid PETG A1": ("clip_filamento_bambu-A1.3mf", 0),
    "Elegoo Rapid PETG 2": ("juego_para_gatos-A1.3mf", 0),
}

# Lists holding a fixed number of values per filament (besides the 1-per-filament keys)
CHUNK_KEYS = {
    "filament_dev_ams_drying_ams_limitations": 2,
    "flush_volumes_vector": 2,
    "filament_dev_ams_drying_temperature": 4,
    "filament_dev_ams_drying_time": 4,
}

# Rebuilt by the converter for the actual slot count, or tied to the source project's plates
STRUCTURAL_KEYS = {"different_settings_to_system", "inherits_group", "flush_volumes_matrix",
                   "wipe_tower_x", "wipe_tower_y"}


def load(folder, name):
    with zipfile.ZipFile(os.path.join(folder, name)) as z:
        return json.loads(z.read("Metadata/project_settings.config"))


def filament_count(cfg):
    return len(cfg["filament_settings_id"])


def main(folder):
    configs = {name: load(folder, name) for name in
               {BASE_FILE, *PRINT_SOURCES.values(), *(f for f, _ in FILAMENT_SOURCES.values())}}

    # One value per filament in every sample file (files have 1 and 2 filaments)
    per_filament = sorted(k for k in configs[BASE_FILE]
                          if k not in CHUNK_KEYS
                          and all(isinstance(c.get(k), list) and len(c[k]) == filament_count(c)
                                  for c in configs.values()))

    base = dict(configs[BASE_FILE])
    for key in per_filament + list(CHUNK_KEYS) + ["flush_volumes_matrix"]:
        base.pop(key)

    filaments = {}
    for name, (file, idx) in FILAMENT_SOURCES.items():
        cfg = configs[file]
        if cfg["filament_settings_id"][idx] != name:
            raise SystemExit(f"{file}[{idx}] is {cfg['filament_settings_id'][idx]!r}, expected {name!r}")
        filaments[name] = {
            "type": cfg["filament_type"][idx],
            "inherits": cfg["inherits_group"][1 + idx],
            "diff": cfg["different_settings_to_system"][1 + idx],
            "values": {k: cfg[k][idx] for k in per_filament},
            "chunks": {k: cfg[k][idx * w:(idx + 1) * w] for k, w in CHUNK_KEYS.items()},
        }

    base_cfg = configs[BASE_FILE]
    prints = {}
    for name, file in PRINT_SOURCES.items():
        cfg = configs[file]
        if cfg["print_settings_id"] != name:
            raise SystemExit(f"{file} uses {cfg['print_settings_id']!r}, expected {name!r}")
        delta = {k: v for k, v in cfg.items()
                 if k not in per_filament and k not in CHUNK_KEYS and k not in STRUCTURAL_KEYS
                 and base_cfg.get(k) != v}
        prints[name] = {
            "inherits": cfg["inherits_group"][0],
            "diff": cfg["different_settings_to_system"][0],
            "delta": delta,
        }

    data = {
        "source": {"application": base_cfg.get("version"), "base_file": BASE_FILE},
        "base": base,
        "printer_inherits": base_cfg["inherits_group"][-1],
        "printer_diff": base_cfg["different_settings_to_system"][-1],
        "per_filament_keys": per_filament,
        "chunk_keys": CHUNK_KEYS,
        "print_profiles": prints,
        "filament_profiles": filaments,
    }

    out = os.path.join(os.path.dirname(__file__), "..", "extension", "src", "lib", "targets", "a1-profiles.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/extract_a1_profiles.py — do not edit\n")
        f.write("self.C3MF = self.C3MF || {};\n\n")
        f.write("self.C3MF.A1_DATA = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
    print(f"wrote {os.path.normpath(out)}: {len(per_filament)} per-filament keys, "
          f"{len(prints)} print profiles, {len(filaments)} filament profiles, "
          f"print deltas: { {n: len(p['delta']) for n, p in prints.items()} }")


if __name__ == "__main__":
    main(sys.argv[1])
